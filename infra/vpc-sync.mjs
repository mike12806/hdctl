#!/usr/bin/env node
// Keeps infra/targets.json, the account's Workers VPC Services, and the
// [[vpc_services]] block in worker/wrangler.toml in step.
//
//   node infra/vpc-sync.mjs          create missing services, write ids back,
//                                    regenerate the wrangler.toml block
//   node infra/vpc-sync.mjs --check  no API calls; fail if a target has no
//                                    serviceId or the block is out of date (CI)
//
// Creating a VPC Service needs a token with Connectivity Directory Admin
// (CLOUDFLARE_API_TOKEN + CLOUDFLARE_ACCOUNT_ID). Deploying only needs Bind.
// A service is matched by name first, so re-running after a partial failure
// adopts what was already created instead of making duplicates.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const targetsPath = join(root, "infra/targets.json");
const wranglerPath = join(root, "worker/wrangler.toml");
const BEGIN = "# BEGIN vpc_services";
const END = "# END vpc_services";
const check = process.argv.includes("--check");

const catalog = JSON.parse(readFileSync(targetsPath, "utf8"));

function wrangler(args) {
  return execFileSync("npx", ["--yes", "wrangler@4", ...args], {
    cwd: join(root, "worker"),
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
}

/** name -> id for every VPC Service on the account. */
function existingServices() {
  const out = wrangler(["vpc", "service", "list"]);
  const byName = new Map();
  for (const m of out.matchAll(/│\s*([0-9a-f-]{36})\s*│\s*(\S+)\s*│/g)) byName.set(m[2], m[1]);
  return byName;
}

function createArgs(t) {
  const args = ["vpc", "service", "create", t.service, "--type", "http", "--tunnel-id", catalog.tunnelId];
  if (t.address.ipv4) args.push("--ipv4", t.address.ipv4);
  else if (t.address.hostname) args.push("--hostname", t.address.hostname);
  else throw new Error(`${t.id}: address needs ipv4 or hostname`);
  args.push(t.scheme === "https" ? "--https-port" : "--http-port", String(t.port));
  if (t.scheme === "https") args.push("--cert-verification-mode", t.certVerification ?? "verify_full");
  return args;
}

/** Add `"serviceId": "<id>"` to the target's one-line entry, keeping the file's layout. */
function writeServiceId(text, id, serviceId) {
  const lines = text.split("\n");
  const i = lines.findIndex((l) => l.includes(`"id": "${id}",`));
  if (i < 0) throw new Error(`could not find the line for target ${id}`);
  lines[i] = lines[i].replace(/\s*}(,?)\s*$/, `, "serviceId": "${serviceId}" }$1`);
  return lines.join("\n");
}

function renderBlock(targets) {
  const body = targets
    .map((t) => `[[vpc_services]]\nbinding = "${t.binding}"\nservice_id = "${t.serviceId}"\nremote = true`)
    .join("\n\n");
  return `${BEGIN} (generated by \`npm run vpc:sync\` from infra/targets.json; do not edit by hand)\n${body}\n${END}`;
}

function replaceBlock(toml, block) {
  const start = toml.indexOf(BEGIN);
  const end = toml.indexOf(END);
  if (start < 0 || end < 0) throw new Error(`worker/wrangler.toml needs "${BEGIN}" and "${END}" marker lines`);
  return toml.slice(0, start) + block + toml.slice(end + END.length);
}

// Duplicate bindings or services would make the generated block ambiguous.
for (const key of ["id", "binding", "service"]) {
  const seen = new Set();
  for (const t of catalog.targets) {
    if (seen.has(t[key])) throw new Error(`duplicate ${key} "${t[key]}" in infra/targets.json`);
    seen.add(t[key]);
  }
}

if (check) {
  const missing = catalog.targets.filter((t) => !t.serviceId).map((t) => t.id);
  const toml = readFileSync(wranglerPath, "utf8");
  const stale = replaceBlock(toml, renderBlock(catalog.targets)) !== toml;
  if (missing.length) console.error(`Targets without a serviceId (run npm run vpc:sync): ${missing.join(", ")}`);
  if (stale) console.error("worker/wrangler.toml's [[vpc_services]] block is out of date (run npm run vpc:sync)");
  process.exit(missing.length || stale ? 1 : 0);
}

let text = readFileSync(targetsPath, "utf8");
const pending = catalog.targets.filter((t) => !t.serviceId);
if (pending.length) {
  const existing = existingServices();
  for (const t of pending) {
    let id = existing.get(t.service);
    if (id) {
      console.log(`= ${t.service} already exists (${id})`);
    } else {
      const out = wrangler(createArgs(t));
      id = out.match(/Created VPC service:\s*([0-9a-f-]{36})/)?.[1];
      if (!id) throw new Error(`could not read the new id for ${t.service} from:\n${out}`);
      console.log(`+ ${t.service} -> ${t.address.ipv4 ?? t.address.hostname}:${t.port} (${id})`);
    }
    t.serviceId = id;
    text = writeServiceId(text, t.id, id);
    writeFileSync(targetsPath, text); // after each one, so a failure part-way loses nothing
  }
}

const toml = readFileSync(wranglerPath, "utf8");
const next = replaceBlock(toml, renderBlock(catalog.targets));
if (next !== toml) {
  writeFileSync(wranglerPath, next);
  console.log("Updated worker/wrangler.toml");
} else {
  console.log("worker/wrangler.toml already up to date");
}
